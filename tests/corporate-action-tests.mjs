import assert from 'node:assert/strict';
import {splitLedger,normalizeShareSeries} from '../assets/report/share-basis.mjs';
const action={date:'2026-06-01',known_at:'2026-06-01',ratio:1.241,type:'unclassified_action',source:'Yahoo Finance'},data={cik:'1048911',asOf:'2026-10-30',facts:{}},series={eps_diluted:[{start:'2025-06-01',end:'2026-05-31',filed:'2026-07-20',val:18.55}],shares_diluted:[{start:'2025-06-01',end:'2026-05-31',filed:'2026-07-20',val:235e6}]},feed={status:'available',events:[action]},before=JSON.stringify(feed),ledger=splitLedger(data,feed),normalized=normalizeShareSeries(series,ledger);
assert.equal(ledger.events.length,0);assert.equal(ledger.non_share_actions.length,1);
assert.equal(ledger.non_share_actions[0].share_basis_effect,'none');
assert.match(ledger.non_share_actions[0].source_url,/1048911/);
assert.equal(JSON.stringify(feed),before,'Vendor input remains immutable');
assert.equal(normalized.series.eps_diluted[0].val,18.55);
assert.equal(normalized.series.eps_diluted[0].normalization.factor,1);
assert.equal(normalized.series.shares_diluted[0].val,235e6);
const wrong=splitLedger({...data,cik:'1'},feed);
assert.equal(wrong.events[0].unresolved,true,'A different company does not inherit classification');
const near=splitLedger(data,{...feed,events:[{...action,date:'2026-06-02'}]});
assert.equal(near.events[0].unresolved,true,'A nearby event is not automatically the same action');
const unknown=splitLedger(data,{...feed,events:[{...action,source:'Unknown vendor'}]});
assert.equal(unknown.events[0].unresolved,true);
const explicit=splitLedger(data,{...feed,events:[{...action,type:'split',ratio:2}]});
assert.equal(explicit.events.length,1,'A real explicitly classified split is never removed by this registry');
const history=splitLedger(data,feed,{knowledge_as_of:'2026-05-31',target_share_basis:'2026-05-31',mode:'point_in_time'});
assert.equal(history.non_share_actions.length,0,'No future disclosure leaks into historical knowledge');
assert.equal(history.events.length,0);
