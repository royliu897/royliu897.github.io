assert.deepEqual(chartSeries([[2023,50],[2024,75]],2023,2024,'indexed'),[[2023,100],[2024,150]]);
assert.throws(()=>chartSeries([[2023,0],[2024,3]],2023,2024,'indexed'));
assert.deepEqual(chartSeries([[2023,-2],[2024,3]],2024,2024,'growth'),[]);
