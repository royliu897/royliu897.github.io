import assert from 'node:assert/strict';
import {epsPath,projectedPrice,discountedPrice,migrateGrowth} from '../assets/research/valuation-flow.mjs';
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} != ${b}`);
const base={eps:10,years:3,exitPE:15};
assert.deepEqual(epsPath({...base,growth:'.5'}),[10.5,11,11.5]);
assert.deepEqual(epsPath({...base,growth:'0'}),[10,10,10]);
near(projectedPrice({...base,growth:'.05x'}),10*1.05**3*15);
assert.deepEqual(epsPath({...base,growth:'.5*(2*t-1)'}),[10.5,12,14.5]);
near(epsPath({...base,years:1,growth:'.01x^2'})[0],11);
const old={...base,growth:'.05+.01*t'};
near(projectedPrice(migrateGrowth(old)),10*1.05*1.06*1.07*15);
assert.deepEqual(migrateGrowth(migrateGrowth(old)),migrateGrowth(old));
assert.throws(()=>epsPath({...base,growth:'-20'}));
assert.throws(()=>epsPath({...base,growth:'alert(1)'}));
assert.throws(()=>epsPath({...base,growth:'x/0'}));
const linked={...base,price:100,growth:'.5',discountYears:3,hurdle:.1,dividend:2,divGrowth:'0'};linked.expectedPrice=projectedPrice(linked);
const result=discountedPrice(linked);assert.deepEqual(result.rows.map(r=>r.eps),[10.5,11,11.5]);near(result.exit,172.5);
const independent=discountedPrice({...linked,eps:0,expectedPrice:121,discountYears:2,dividend:0});near(independent.pv,100);near(independent.irr,.1);
console.log('EPS expressions: scalar, compounding, time, quadratic, migration, linked discounting and invalid input checks passed.');
