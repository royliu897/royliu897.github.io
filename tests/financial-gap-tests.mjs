import fs from 'node:fs';
import assert from 'node:assert/strict';
import {toReportPayload} from '../assets/report/sec-adapter.mjs';
import {parseYahooSplits} from '../sec-worker/split-feed.mjs';
import {resolveDefinition,definitionTokens,definitionById,definitionCount} from '../assets/report/definition-graph.mjs';
const read=name=>JSON.parse(fs.readFileSync(new URL('./fixtures/'+name,import.meta.url)));
const data=read('aapl-financial-gap-facts.json'),snapshot=JSON.stringify(data),feed=parseYahooSplits(read('aapl-yahoo-splits.json'),'AAPL','320193','2026-10-29T00:00:00Z');
const annual=toReportPayload(data,{}, {price:343.83,currency:'USD'},'annual','AAPL',{split_feed:feed,knowledge_as_of:'2026-10-29'});
const value=(payload,table,key,period='2025')=>payload.financials[table].find(r=>r.key===key)?.values[period];
assert.equal(value(annual,'cash_flow','cf_working_capital'),-25000);
assert.equal(value(annual,'cash_flow','cf_other_operating'),-89);
assert.equal(value(annual,'cash_flow','cf_investments'),29390);
assert.equal(value(annual,'cash_flow','cf_other_investing'),-1480);
assert.equal(value(annual,'cash_flow','cf_other_financing'),-6071);
assert.equal(value(annual,'balance_sheet','tax_payable'),13016);
assert.equal(value(annual,'balance_sheet','other_equity'),0);
assert.equal(value(annual,'income_statement','other_nonrecurring'),undefined,'Do not manufacture vendor-only nonrecurring adjustments');
assert.equal(JSON.stringify(data),snapshot,'Residual computation does not mutate source facts');
assert.ok(annual.historical_prices['2025-09']>0,'Historical prices populate from the existing split-history response');
assert.ok(annual.historical_prices['2015-09']>0);
assert.equal(toReportPayload(data,{},null,'annual','',{split_feed:{...feed,currency:'EUR'}}).historical_prices['2025-09'],undefined,'Do not mix quote currencies');
const rows=annual.financials.cash_flow;
for(const [total,keys]of [['cash_from_operations',['cf_net_income','cf_dna','cf_working_capital','cf_deferred_tax','cf_stock_comp','cf_other_operating']],['cash_from_investing',['cf_capex','cf_acquisitions','cf_investments','cf_other_investing']],['cash_from_financing',['cf_net_stock','cf_debt_net','cf_net_preferred','cf_dividends','cf_other_financing']]])assert.equal(value(annual,'cash_flow',total),keys.reduce((n,k)=>n+(value(annual,'cash_flow',k)||0),0),total+' reconciles');
const mcd=toReportPayload(read('mcd-report-facts.json'));
assert.ok(value(mcd,'income_statement','interest_expense')<0,'Non-bank interest expense is negative');
const root=resolveDefinition({label:'ROIC',group:'10-Yr Median Returns'});
assert.equal(root.formula,'Median of: Annual net income ÷ average invested capital × 100');
const child=definitionTokens(root.formula,root.id).find(t=>t.text.toLowerCase()==='average invested capital');
assert.equal(child.ref,'average_invested_capital');
assert.ok(definitionTokens(definitionById(child.ref).formula,child.ref).some(t=>t.ref==='invested_capital'));
assert.ok(definitionTokens(definitionById('invested_capital').formula,'invested_capital').some(t=>t.ref==='shareholders_equity'));
assert.ok(definitionCount>100);
assert.equal(resolveDefinition({label:'Other',metricKey:'cf_other_operating'}).formula.startsWith('Operating cash flow'),true);
console.log('Financial gap tests pass: recorded Apple cash-flow reconciliation/tax payable/equity, signed interest expense, price currency/history, immutable source data and recursive definition links.');
